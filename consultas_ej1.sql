SELECT APELLIDO, DATE_FORMAT(FECHA_ALTA,'%e de %M de %Y')
FROM empleados;

SELECT CONCAT(SUBSTR(APELLIDO,1,5),'.') "supr. 3 ultimas letras"
FROM empleados
	WHERE LENGTH (APELLIDO) > 6
	ORDER BY APELLIDO;
	
SELECT APELLIDO,
       SALARIO * 0.03 AS Regalo
FROM empleados
	WHERE comision IS NULL
	ORDER BY apellido;
	
SELECT APELLIDO,
	SALARIO + IFNULL(COMISION,0) AS Salario_total
FROM empleados
	WHERE SALARIO + COMISION > 2000
	OR SALARIO > 1800
	OR COMISION > 500;
	
SELECT EMP_NO,APELLIDO,OFICIO,FECHA_ALTA,SALARIO,COMISION,DEP_NO
FROM empleados
	WHERE OFICIO = 'DIRECTOR'
	ORDER BY FECHA_ALTA ASC
	LIMIT 1;
	
SELECT EMP_NO,APELLIDO,OFICIO,DIRECTOR,FECHA_ALTA,SALARIO,COMISION,DEP_NO
FROM empleados
	WHERE DEP_NO = 20 OR DEP_NO = 30
	ORDER BY SALARIO DESC
	LIMIT 2;